@register.simple_tag
def icon(name: str, css: str = "w-5 h-5"):
    path = _PATHS.get(name, _PATHS["shield"])
    return format_html(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" '
        'stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" '
        'class="{}" aria-hidden="true">{}</svg>',
        css,
        mark_safe(path),  # noqa: S308  # nosec B703 B308
    )


@register.filter
def bytes(value, decimals: int = 1) -> str:
    return format_bytes(value, int(decimals))


@register.filter
def bps(value) -> str:
    return format_bps(value)


@register.filter
def duration(value) -> str:
    return format_duration(value)


@register.filter
def datetimefmt(value) -> str:
    return format_datetime(value)


@register.filter
def ago(value) -> str:
    return relative_time(value)


@register.filter
def shorthash(value, length: int = 12) -> str:
    return short_hash(value, int(length))


@register.filter
def percent(value) -> str:
    if value is None:
        return "—"
    return f"{value:.0f}%"


